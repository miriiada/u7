// В отделе маркетинга 4 сотрудника. Напиши программу, которая:
// 1. Создаёт массив сотрудников
// 2. Добавляет нового сотрудника
// 3. Удаляет уволенного сотрудника
// 4. Выводит итоговый список

// Исходный список
const team = ['Иванов', 'Петрова', 'Сидоров'];
console.log('Отдел:', team);

// К нам пришёл новый сотрудник — Козлова
// Используй push, чтобы добавить её в конец
team.push('Козлова');
console.log('После приёма:', team);

// Петрова уволилась — удали её через shift или indexOf + splice
// Петрова — второй элемент (индекс 1)
// Подсказка: arr.splice(индекс, количество)
team.splice(1, 1);
console.log('После увольнения:', team);

// Используй Set, чтобы убедиться, что в отделе нет дубликатов
// (мало ли, случайно добавили того же человека дважды)
const uniqueTeam = [...new Set(team)];
console.log('Уникальные:', uniqueTeam);

// Выведи итоговую численность отдела
console.log('Численность:', team.length);

