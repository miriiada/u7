// Отдел маркетинга. Данные по окладам хранятся в объекте.
// Напиши программу, которая:
// 1. Создаёт объект окладов сотрудников
// 2. Добавляет нового сотрудника
// 3. Выводит оклад каждого через for...in
// 4. Считает общий фонд оплаты труда

// Исходные оклады
const salaries = {
    Иванов: 500000,
    Петрова: 450000,
    Сидоров: 480000,
};

// 1. Добавь Козлову с окладом 520000
salaries.Козлова = 520000;

// 2. Выведи оклады всех сотрудников через for...in
//    Используй интерполяцию: 'Имя: оклад тг'
console.log('=== Оклады сотрудников ===');
for (let name in salaries) {
    console.log(name + ': ' + salaries[name] + ' тг');
}

// 3. Посчитай и выведи общий фонд оплаты труда (ФОТ)
//    Пройди по всем ключам salaries и суммируй
let total = 0;
for (let name in salaries) {
    total += salaries[name];
}
console.log('ФОТ отдела: ' + total + ' тг');

// 4. Проверь, есть ли сотрудник с фамилией 'Иванов'
console.log('Иванов в штате:', 'Иванов' in salaries);

