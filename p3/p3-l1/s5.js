// Напиши функцию isPositive, которая принимает число и возвращает true, если число положительное,
// и false — если ноль или отрицательное.
// Проверь её на числах: 5, 0, -3

// Твой код:

function isPositive (a) {
    if (a > 0) {
        return true;
    } else {
        return false;
    }
}

console.log(isPositive(0));